// treatments/lumenary/build.mjs
// Bundles every treatment in vendor/lumenary (Mursal Furqan Kumbhar's Lumenary) into one classic script,
// treatments/lumenary/lumenary.js, which sets window.Lumenary. A classic script so pages still open from file://.
//
//   node treatments/lumenary/build.mjs
//
// Lumenary's own styles/index.js finds styles with import.meta.glob, which only Vite understands, so this
// writes an entry file that imports each style explicitly instead. Nothing in vendor/ is changed.
import { readdirSync, writeFileSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const engine = join(root, 'vendor', 'lumenary', 'src', 'engine');
const rel = (p) => './' + relative(here, p).split('\\').join('/');

const files = readdirSync(join(engine, 'styles')).filter((f) => f.endsWith('.js') && f !== 'index.js').sort();
const imports = files.map((f, i) => `import s${i} from ${JSON.stringify(rel(join(engine, 'styles', f)))};`);

const entry = `// GENERATED by build.mjs. Do not edit.
${imports.join('\n')}
import { registerStyles } from ${JSON.stringify(rel(join(engine, 'registry.js')))};
import { SECTIONS, slugify } from ${JSON.stringify(rel(join(root, 'data', 'sections.js')))};
import { fitSize, scaleCanvas } from ${JSON.stringify(rel(join(engine, 'utils.js')))};
import { makeSample } from ${JSON.stringify(rel(join(engine, 'sample.js')))};
import { bridge } from './bridge.js';

const ALL = [${files.map((_, i) => `s${i}`).join(', ')}];
registerStyles(ALL);
window.Lumenary = bridge({ ALL, SECTIONS, slugify, fitSize, scaleCanvas, makeSample });
`;
writeFileSync(join(here, 'entry.generated.js'), entry);

const out = join(here, 'lumenary.js');
execFileSync('npx', ['-y', 'esbuild@0.24.0', join(here, 'entry.generated.js'), '--bundle', '--format=iife',
  '--target=es2020', '--minify', '--legal-comments=inline', '--log-level=warning',
  // The subject-aware treatments read the model from BASE_URL + "models/u2netp.onnx". Point it at the vendored copy,
  // relative to a page in treatments/. (Fetching it needs a local web server; browsers block it from file://.)
  '--define:import.meta.env={"BASE_URL":"../vendor/lumenary/public/"}',
  `--banner:js=/* Lumenary treatments by Mursal Furqan Kumbhar, https://github.com/mursalfk/lumenary. Bundled for patternbook from vendor/lumenary; see vendor/lumenary/NOTICE.md. */`,
  `--outfile=${out}`], { stdio: 'inherit', cwd: root });
console.log(`bundled ${files.length} treatments into ${relative(root, out)} (${Math.round(statSync(out).size / 1024)} KB)`);
