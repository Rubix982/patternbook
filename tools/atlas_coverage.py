"""Regenerate atlas/coverage.md from the atlas's domain files (every table row is an element).
  python3 -I tools/atlas_coverage.py
First written for C-015 (as runs/c015/merge_atlas.py), made a tool in C-016 when the atlas began to be edited in place."""
import collections, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, 'atlas')
ORDER = ['architecture', 'gardens-and-water', 'textiles-and-dress', 'jewellery-and-adornment', 'body-and-floor',
         'painting-and-depiction', 'objects-and-crafts', 'script-and-lettering', 'street-transport-and-signs',
         'ritual-and-festival-objects']
COUNTRIES = ['India', 'Pakistan', 'Bangladesh', 'Nepal', 'Bhutan', 'Sri Lanka', 'Maldives']
rows = []
for slug in ORDER:
    dom = fam = None
    for line in open(os.path.join(A, slug + '.md')):
        if line.startswith('# '): dom = line[2:].strip()
        elif line.startswith('## '): fam = line[3:].strip()
        elif line.startswith('| ') and not line.startswith('| element') and not line.startswith('|---'):
            c = [x.strip() for x in line.strip().strip('|').split('|')]
            nb = len([b for b in c[3].split(';') if b.strip() and b.strip() not in ('—', '-')])
            rows.append(dict(domain=dom, family=fam, regions=c[2], branches=nb, first=c[5].lower().startswith('y')))
N = len(rows); M = sum(r['first'] for r in rows); B = sum(r['branches'] for r in rows)
cov = collections.OrderedDict()
for r in rows:
    d = cov.setdefault(r['domain'], collections.OrderedDict()).setdefault(r['family'], [0, 0, 0])
    d[0] += 1; d[1] += r['branches']; d[2] += r['first']
cc = collections.Counter(); none = india_only = 0
for r in rows:
    hit = [c for c in COUNTRIES if re.search(r'\b' + c + r'\b', r['regions'])]
    cc.update(hit); none += not hit; india_only += hit == ['India']
out = ['# Coverage\n', '_Generated by `tools/atlas_coverage.py` from the domain files; not edited by hand._\n',
       f'**{N} elements** across {len(cov)} domains, **{B} candidate branches**. {M} were in the first-pass sketch; '
       f'**{N - M} ({(N - M) / N:.0%}) were found only by the sources.**\n',
       '## By domain and family\n', '| domain | family | elements | candidate branches | in first pass |', '|---|---|---|---|---|']
for d, fs in cov.items():
    for fam, (n, b, m) in fs.items(): out.append(f'| {d} | {fam} | {n} | {b} | {m} |')
    out.append(f'| **{d}** | | **{sum(v[0] for v in fs.values())}** | **{sum(v[1] for v in fs.values())}** | **{sum(v[2] for v in fs.values())}** |')
out += ['\n## Countries the sources name\n',
        'Counted from the regions column of every element. An element counts for each country its sources name.\n',
        '| country | elements |', '|---|---|'] + [f'| {k} | {cc[k]} |' for k in COUNTRIES] + [f'| none named | {none} |',
        f'\n{india_only} elements ({india_only / N:.0%}) are attested for India alone. This measures the sources as much '
        'as the subject: C-016 found that English Wikipedia undercounts Pakistan\'s textiles and dress by at least 56 %, '
        'and the same check has not yet been run for India (T-020).']
open(os.path.join(A, 'coverage.md'), 'w').write('\n'.join(out) + '\n')
print(N, 'elements;', dict(cc), 'india only', india_only)
