// engine/catalog.mjs
// Writes CATALOG.md: every style in styles/ with its section, kind, one-line description and dials,
// as a menu for an agent building a page. Run: node engine/catalog.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { SECTIONS, slugify } = await import(pathToFileURL(join(here, 'sections.js')).href);
const byId = {};
for (const f of readdirSync(join(here, 'styles')).filter((f) => f.endsWith('.js') && f !== 'index.js')) {
  const s = (await import(pathToFileURL(join(here, 'styles', f)).href)).default;
  byId[s.id] = s;
}

const dial = (p) => {
  if (p.type === 'select') return `${p.key}=${p.default} (${(p.options || []).map((o) => (Array.isArray(o) ? o[0] : o)).join('|')})`;
  if (p.type === 'range') return `${p.key}=${p.default} [${p.min}–${p.max}]`;
  if (p.type === 'shuffle') return `${p.key}=${p.default} (seed)`;
  return `${p.key}=${JSON.stringify(p.default)}`;
};

const out = [
  '# Style catalogue',
  '',
  'Generated by `engine/catalog.mjs` from `engine/styles/`. Sections A to N are the styles that came from Lumenary, by Mursal Furqan Kumbhar (https://github.com/mursalfk/lumenary, used with his permission; see `engine/NOTICE.md`); section P is patternbook\'s own, each rendering a picture through a process modelled in `engine/core/`.',
  '',
  '**still:** drawn once. **live:** animated, responds to the pointer. Dials are `key=default`, with options or [min–max].',
  '',
];
let n = 0;
for (const sec of SECTIONS.filter((s) => s.enabled)) {
  out.push(`## ${sec.letter}. ${sec.title}`, '', sec.blurb, '');
  for (const name of sec.items) {
    const s = byId[slugify(name)];
    if (!s) continue;
    n++;
    const kind = s.kind === 'still' ? 'still' : 'live';
    out.push(`- **\`${s.id}\`** (${kind}): ${s.blurb || s.name}  \n  dials: ${(s.params || []).map(dial).join('; ') || 'none'}`);
  }
  out.push('');
}
writeFileSync(join(here, 'CATALOG.md'), out.join('\n'));
console.log(`wrote CATALOG.md with ${n} treatments`);
