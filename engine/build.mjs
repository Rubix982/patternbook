// engine/build.mjs
// Bundles the whole engine into one classic script, engine/engine.js, which sets window.PatternbookEngine:
//   - the process models in core/ (PatternbookEngine.weave, .kantha, .dye, ...), as engine/index.js exports them;
//   - every style in styles/ (picture in, treated picture out), with the studio API over them
//     (PatternbookEngine.studio: list, render, renderAsync, animate, applyImageData, sample; see studio.js).
// A classic script, so pages opened straight from disk (file://) load it; browsers won't load ES modules there.
//
//   node engine/build.mjs        (uses npx esbuild@0.24.0)
//
// styles/index.js finds styles with import.meta.glob, which only Vite understands, so this writes an entry file
// (entry.generated.js) that imports each style by name instead.
import { readdirSync, writeFileSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const files = readdirSync(join(here, 'styles')).filter((f) => f.endsWith('.js') && f !== 'index.js').sort();
const imports = files.map((f, i) => `import s${i} from ${JSON.stringify('./styles/' + f)};`);

const entry = `// GENERATED by build.mjs. Do not edit.
${imports.join('\n')}
import { registerStyles } from './registry.js';
import { SECTIONS, slugify } from './sections.js';
import { fitSize, scaleCanvas } from './utils.js';
import { makeSample } from './sample.js';
import { bridge } from './studio.js';
export * from './index.js';

const ALL = [${files.map((_, i) => `s${i}`).join(', ')}];
registerStyles(ALL);
export const studio = typeof document === 'undefined' ? null : bridge({ ALL, SECTIONS, slugify, fitSize, scaleCanvas, makeSample });
`;
writeFileSync(join(here, 'entry.generated.js'), entry);

const out = join(here, 'engine.js');
// The subject-aware styles read their model from import.meta.env.BASE_URL + "models/u2netp.onnx". The banner points
// that at this folder, wherever the page that loads the bundle is (fetching the model needs a local web server).
const banner = '/* patternbook engine, bundled by engine/build.mjs; edit the sources in engine/, not this file. The styles that came ' +
  'from Lumenary are by Mursal Furqan Kumbhar (https://github.com/mursalfk/lumenary), used with his permission; see engine/NOTICE.md. */ ' +
  'var __ENGINE_ENV = { BASE_URL: (typeof document !== "undefined" && document.currentScript) ? document.currentScript.src.replace(/[^/]*$/, "") : "./" };';
execFileSync('npx', ['-y', 'esbuild@0.24.0', join(here, 'entry.generated.js'), '--bundle', '--format=iife', '--global-name=PatternbookEngine',
  '--target=es2020', '--minify', '--legal-comments=inline', '--log-level=warning', '--define:import.meta.env=__ENGINE_ENV',
  `--banner:js=${banner}`, `--outfile=${out}`], { stdio: 'inherit', cwd: root });
console.log(`bundled ${files.length} styles and core/ into ${relative(root, out)} (${Math.round(statSync(out).size / 1024)} KB)`);
